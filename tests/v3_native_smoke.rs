//! Native smoke test for the v3 transact prover (#350): the exact scenario the
//! core fixture uses (1000-unit input at leaf 0 + zero dummy, outputs 400+100,
//! ext_amount −500) proven through the WASM-exported `prove_transact` code
//! path with the persistent dev proving key, then verified against the
//! persistent verifying key — proving the browser prover and the on-chain VK
//! constants share one key. Runs natively (no JS interop on the happy path).

use ark_bn254::{Bn254, Fr};
use ark_ff::{BigInteger, PrimeField};
use ark_serialize::CanonicalDeserialize;

use paraloom_prover_wasm::{prove_transact, v3_note_commitment, v3_note_pubkey};

const KEYS_DIR: &str = "../paraloom-core/keys";

fn fr_to_le(f: &Fr) -> [u8; 32] {
    let mut out = [0u8; 32];
    let le = f.into_bigint().to_bytes_le();
    out[..le.len().min(32)].copy_from_slice(&le[..le.len().min(32)]);
    out
}

fn hx(b: &[u8; 32]) -> String {
    hex::encode(b)
}

/// True if the proving key was produced under the circom convention, which is
/// what `snarkjs groth16 setup` and our `Groth16ProofSystem::setup` both emit.
/// Told apart by `h_query`: circom carries one point per domain element, the
/// arkworks-native reduction one fewer.
fn key_is_circom_convention(pk_bytes: &[u8]) -> bool {
    use ark_serialize::CanonicalDeserialize;
    match ark_groth16::ProvingKey::<ark_bn254::Bn254>::deserialize_compressed(pk_bytes) {
        Ok(pk) => pk.h_query.len().is_power_of_two(),
        Err(_) => false,
    }
}

#[test]
fn prove_transact_roundtrips_against_the_persistent_keys() {
    let pk_bytes = match std::fs::read(format!("{KEYS_DIR}/transact_v3_proving.key")) {
        Ok(b) => b,
        // The keys are gitignored; on a machine without them (CI) there is
        // nothing to prove against — the core repo's tests cover the circuit.
        Err(_) => {
            eprintln!("persistent keys not present; skipping");
            return;
        }
    };
    let vk_bytes =
        std::fs::read(format!("{KEYS_DIR}/transact_v3_verifying.key")).expect("verifying key");

    // The prover proves under `CircomReduction`, because the production key
    // comes from the phase-2 ceremony via snarkjs (#659). A key generated by
    // the older arkworks-native setup cannot be proved against it — the two
    // differ in `h_query`, which is domain-many for one and domain-1 for the
    // other. Skip rather than fail on a stale local key: this is what a
    // machine that has not yet taken the ceremony key looks like, and the
    // failure would say nothing useful.
    if !key_is_circom_convention(&pk_bytes) {
        eprintln!(
            "keys/ holds a pre-ceremony arkworks-native key; skipping. \
             Regenerate from the ceremony zkey to exercise this."
        );
        return;
    }

    // The zero-subtree sibling list for leaf 0 of an empty 32-level tree, and
    // the root after inserting the input note there (all-left fold).
    use paraloom_prover_wasm::privacy::poseidon_circom::{v3_commit, v3_merkle_pair, v3_pubkey};
    let mut zeros = vec![Fr::from(0u64)];
    for k in 0..32 {
        zeros.push(v3_merkle_pair(zeros[k], zeros[k]));
    }

    let sk0 = Fr::from(51u64);
    let bl0 = Fr::from(5u64);
    let c0 = v3_commit(Fr::from(1000u64), v3_pubkey(sk0), bl0, Fr::from(0u64));
    let mut root = c0;
    for z in zeros.iter().take(32) {
        root = v3_merkle_pair(root, *z);
    }

    let path_hex: Vec<String> = zeros[..32].iter().map(|z| hx(&fr_to_le(z))).collect();
    let path_json = serde_json::to_string(&path_hex).unwrap();

    let inputs = format!(
        r#"[
          {{"amount":1000,"privkey_hex":"{}","blinding_hex":"{}","leaf_index":0,"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{}","blinding_hex":"{}","leaf_index":0,"path_hex":{path_json}}}
        ]"#,
        hx(&fr_to_le(&Fr::from(51u64))),
        hx(&fr_to_le(&Fr::from(5u64))),
        hx(&fr_to_le(&Fr::from(52u64))),
        hx(&fr_to_le(&Fr::from(6u64))),
    );
    let opk0 = v3_note_pubkey(&hx(&fr_to_le(&Fr::from(61u64)))).unwrap();
    let opk1 = v3_note_pubkey(&hx(&fr_to_le(&Fr::from(62u64)))).unwrap();
    let outputs = format!(
        r#"[
          {{"amount":400,"pubkey_hex":"{opk0}","blinding_hex":"{}"}},
          {{"amount":100,"pubkey_hex":"{opk1}","blinding_hex":"{}"}}
        ]"#,
        hx(&fr_to_le(&Fr::from(1u64))),
        hx(&fr_to_le(&Fr::from(2u64))),
    );

    let recipient = [3u8; 32];
    let native_asset = [0u8; 32];
    let out = prove_transact(
        &pk_bytes,
        &hx(&fr_to_le(&root)),
        -500,
        &hx(&recipient),
        &hx(&native_asset),
        &inputs,
        &outputs,
    )
    .expect("prove_transact");

    // Parse the ingress-body JSON.
    let v: serde_json::Value = serde_json::from_str(&out).expect("json out");
    // The "proof" field is the L2 wire form `tag(1) || body` (#686), not a bare
    // compressed proof. Split the suite tag off before deserializing — and
    // check it, so the test also pins that `prove_transact` tags with the v3
    // suite. This is what the earlier version got wrong: it deserialized the
    // tagged bytes directly, which fails on the leading tag byte, and the test
    // never ran in CI (prover-wasm has no workflow) so nothing caught it.
    let wire = hex::decode(v["proof"].as_str().unwrap()).unwrap();
    let (suite, proof_bytes) =
        paraloom_prover_wasm::privacy::proof_codec::split_tagged_proof(&wire)
            .expect("proof carries a valid suite tag");
    assert_eq!(
        suite,
        paraloom_prover_wasm::privacy::proof_codec::ProofSuite::Groth16Bn254TransactV3
    );
    let nf0: [u8; 32] = hex::decode(v["nullifiers"][0].as_str().unwrap())
        .unwrap()
        .try_into()
        .unwrap();
    let nf1: [u8; 32] = hex::decode(v["nullifiers"][1].as_str().unwrap())
        .unwrap()
        .try_into()
        .unwrap();
    let oc0: [u8; 32] = hex::decode(v["output_commitments"][0].as_str().unwrap())
        .unwrap()
        .try_into()
        .unwrap();
    let oc1: [u8; 32] = hex::decode(v["output_commitments"][1].as_str().unwrap())
        .unwrap()
        .try_into()
        .unwrap();

    // The output commitments must equal the wallet-side derivations.
    assert_eq!(
        hex::encode(oc0),
        v3_note_commitment(400, &opk0, &hx(&fr_to_le(&Fr::from(1u64)))).unwrap()
    );

    // Verify against the persistent verifying key with the 8 public inputs in
    // circuit order — the same check the on-chain verifier performs.
    let vk = ark_groth16::VerifyingKey::<Bn254>::deserialize_compressed(&vk_bytes[..]).unwrap();
    let proof = ark_groth16::Proof::<Bn254>::deserialize_compressed(proof_bytes).unwrap();

    let mut hasher = <sha2::Sha256 as sha2::Digest>::new();
    sha2::Digest::update(&mut hasher, recipient);
    sha2::Digest::update(&mut hasher, (-500i64).to_le_bytes());
    let ext_data_hash: [u8; 32] = sha2::Digest::finalize(hasher).into();

    let public_inputs = vec![
        root,
        -Fr::from(500u64),
        Fr::from_le_bytes_mod_order(&ext_data_hash),
        Fr::from(0u64),
        Fr::from_le_bytes_mod_order(&nf0),
        Fr::from_le_bytes_mod_order(&nf1),
        Fr::from_le_bytes_mod_order(&oc0),
        Fr::from_le_bytes_mod_order(&oc1),
    ];
    let ok = ark_groth16::Groth16::<Bn254>::verify_proof(
        &ark_groth16::prepare_verifying_key(&vk),
        &proof,
        &public_inputs,
    )
    .expect("verify");
    assert!(
        ok,
        "browser-path proof must verify against the persistent VK"
    );
}

/// The client-side tree rebuild must produce a path the circuit accepts: prove
/// with a path from `v3_merkle_path` (two real leaves, spending leaf 1) and
/// verify against the persistent VK.
#[test]
fn v3_merkle_path_output_proves_membership() {
    let pk_bytes = match std::fs::read(format!("{KEYS_DIR}/transact_v3_proving.key")) {
        Ok(b) => b,
        Err(_) => {
            eprintln!("persistent keys not present; skipping");
            return;
        }
    };

    use paraloom_prover_wasm::privacy::poseidon_circom::{v3_commit, v3_pubkey};
    use paraloom_prover_wasm::v3_merkle_path;

    // Two deposited notes; we spend the SECOND (leaf 1, the right child).
    let mk = |amt: u64, sk: u64, bl: u64| {
        v3_commit(
            Fr::from(amt),
            v3_pubkey(Fr::from(sk)),
            Fr::from(bl),
            Fr::from(0u64),
        )
    };
    let leaf0 = mk(700, 71, 8);
    let leaf1 = mk(1000, 51, 5);
    let leaves = serde_json::to_string(&[hx(&fr_to_le(&leaf0)), hx(&fr_to_le(&leaf1))]).unwrap();

    let out = v3_merkle_path(&leaves, 1).expect("path");
    let v: serde_json::Value = serde_json::from_str(&out).unwrap();
    let root_hex = v["root"].as_str().unwrap().to_string();
    let path_json = serde_json::to_string(&v["path"]).unwrap();

    let inputs = format!(
        r#"[
          {{"amount":1000,"privkey_hex":"{}","blinding_hex":"{}","leaf_index":1,"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{}","blinding_hex":"{}","leaf_index":0,"path_hex":{path_json}}}
        ]"#,
        hx(&fr_to_le(&Fr::from(51u64))),
        hx(&fr_to_le(&Fr::from(5u64))),
        hx(&fr_to_le(&Fr::from(52u64))),
        hx(&fr_to_le(&Fr::from(6u64))),
    );
    let opk = v3_note_pubkey(&hx(&fr_to_le(&Fr::from(61u64)))).unwrap();
    let outputs = format!(
        r#"[
          {{"amount":400,"pubkey_hex":"{opk}","blinding_hex":"{}"}},
          {{"amount":100,"pubkey_hex":"{opk}","blinding_hex":"{}"}}
        ]"#,
        hx(&fr_to_le(&Fr::from(1u64))),
        hx(&fr_to_le(&Fr::from(2u64))),
    );

    let res = prove_transact(
        &pk_bytes,
        &root_hex,
        -500,
        &hx(&[3u8; 32]),
        &hx(&[0u8; 32]),
        &inputs,
        &outputs,
    );
    assert!(
        res.is_ok(),
        "a v3_merkle_path path must prove membership: {:?}",
        res.err()
    );
}

#[test]
fn prove_transact_rejects_leaf_index_overflow_unbalanced_amounts_and_wrong_root() {
    let z = hx(&[0u8; 32]);
    let path_json = serde_json::to_string(&vec![z.clone(); 32]).unwrap();
    let opk = v3_note_pubkey(&hx(&fr_to_le(&Fr::from(61u64)))).unwrap();

    // 1. leaf_index > u32::MAX must be rejected before circuit synthesis
    // truncates it via `as u32`.
    let overflow_inputs = format!(
        r#"[
          {{"amount":0,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":{},"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}}
        ]"#,
        (u32::MAX as u64) + 1
    );
    let zero_outputs = format!(
        r#"[
          {{"amount":0,"pubkey_hex":"{opk}","blinding_hex":"{z}"}},
          {{"amount":0,"pubkey_hex":"{opk}","blinding_hex":"{z}"}}
        ]"#
    );
    assert!(
        prove_transact(&[], &z, 0, &z, &z, &overflow_inputs, &zero_outputs).is_err(),
        "leaf_index > u32::MAX must be rejected"
    );

    // 2. Unbalanced amounts (sum(inputs) + ext_amount != sum(outputs)) must be
    // rejected before Groth16 proving.
    let valid_idx_inputs = format!(
        r#"[
          {{"amount":1000,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}}
        ]"#
    );
    let unbalanced_outputs = format!(
        r#"[
          {{"amount":600,"pubkey_hex":"{opk}","blinding_hex":"{z}"}},
          {{"amount":100,"pubkey_hex":"{opk}","blinding_hex":"{z}"}}
        ]"#
    );
    assert!(
        prove_transact(&[], &z, -500, &z, &z, &valid_idx_inputs, &unbalanced_outputs).is_err(),
        "unbalanced value conservation must be rejected"
    );

    // 3. Non-zero input whose Merkle path does not fold to `root` must be
    // rejected before Groth16 proving.
    let balanced_outputs = format!(
        r#"[
          {{"amount":400,"pubkey_hex":"{opk}","blinding_hex":"{z}"}},
          {{"amount":100,"pubkey_hex":"{opk}","blinding_hex":"{z}"}}
        ]"#
    );
    assert!(
        prove_transact(&[], &z, -500, &z, &z, &valid_idx_inputs, &balanced_outputs).is_err(),
        "mismatched Merkle root for non-zero input must be rejected"
    );

    // 4. Duplicate input nullifiers (e.g. two zero-value dummy inputs with
    // identical privkey/blinding/leaf_index) must be rejected before circuit
    // synthesis.
    let dup_nullifier_inputs = format!(
        r#"[
          {{"amount":0,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{z}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}}
        ]"#
    );
    assert!(
        prove_transact(&[], &z, 0, &z, &z, &dup_nullifier_inputs, &zero_outputs).is_err(),
        "duplicate input nullifiers must be rejected"
    );

    // 5. Non-canonical BN254 field elements (>= scalar modulus p, such as
    // [0xFF; 32]) must be rejected across v3 helpers and prove_transact rather
    // than silently reduced mod p into unspendable commitments.
    let non_canonical = hx(&[0xFFu8; 32]);
    assert!(
        v3_note_pubkey(&non_canonical).is_err(),
        "v3_note_pubkey must reject non-canonical privkey"
    );
    assert!(
        v3_note_commitment(100, &opk, &non_canonical).is_err(),
        "v3_note_commitment must reject non-canonical blinding"
    );
    let non_canonical_outputs = format!(
        r#"[
          {{"amount":0,"pubkey_hex":"{opk}","blinding_hex":"{non_canonical}"}},
          {{"amount":0,"pubkey_hex":"{opk}","blinding_hex":"{z}"}}
        ]"#
    );
    let distinct_zero_inputs = format!(
        r#"[
          {{"amount":0,"privkey_hex":"{}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}},
          {{"amount":0,"privkey_hex":"{}","blinding_hex":"{z}","leaf_index":0,"path_hex":{path_json}}}
        ]"#,
        hx(&fr_to_le(&Fr::from(1u64))),
        hx(&fr_to_le(&Fr::from(2u64))),
    );
    assert!(
        prove_transact(
            &[],
            &z,
            0,
            &z,
            &z,
            &distinct_zero_inputs,
            &non_canonical_outputs
        )
        .is_err(),
        "prove_transact must reject non-canonical output blinding"
    );
}


